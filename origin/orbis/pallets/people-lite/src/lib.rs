	#[pallet::pallet]
	pub struct Pallet<T>(_);

	#[pallet::config]
	pub trait Config:
		frame_system::Config<
		RuntimeOrigin: From<Origin<Self>> + OriginTrait<PalletsOrigin: TryInto<Origin<Self>>>,
		RuntimeCall: IsSubType<Call<Self>> + Dispatchable<PostInfo = PostDispatchInfo>,
	>
	{
		/// Weight information for extrinsics in this pallet.
		type WeightInfo: WeightInfo;

		/// The origin that can issue quotas to verifiers.
		type AttestationAllowanceManager: EnsureOrigin<Self::RuntimeOrigin>;

		/// Service handling lite people member collection lifecycle.
		type MemberService: AppendOnlyMembers
			+ MembershipProver<
				Crypto: GenerateVerifiable<
					Proof: Send + Sync + DecodeWithMemTracking,
					Signature: Send + Sync + DecodeWithMemTracking,
					Member: DecodeWithMemTracking,
				>,
			>;

		/// Owner location for the lite people collection.
		type CollectionOwner: Get<<Self::MemberService as AppendOnlyMembers>::Location>;

		/// Ring exponent used for the lite people collection.
		#[pallet::constant]
		type LiteRingExponent: Get<RingExponent>;

		/// Onboarding size used when creating the lite people collection.
		#[pallet::constant]
		type LiteOnboardingSize: Get<u32>;

		/// Signature generated by lite people and used by verifiers to claim attestations on their
		/// behalf.
		type AttestationSignature: Verify<Signer: IdentifyAccount<AccountId = Self::AccountId>>
			+ Parameter;

		/// Lite personhood consumer service. Lite people can be automatically registered when
		/// attested.
		type LiteConsumerRegistrar: ConsumerRegistrar<Self::AccountId, Error: Into<DispatchError>>;

		/// A set of helper functions for benchmarking.
		///
		/// The default configuration `()` uses the `SR25519` signature schema.
		#[cfg(feature = "runtime-benchmarks")]
		type BenchmarkHelper: BenchmarkHelper<Self::AccountId, Self::AttestationSignature>;
	}

