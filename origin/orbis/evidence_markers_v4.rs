pub fn emit_evidence_markers_v4(group: &str) {
	let mut emitted = 0usize;
	for &(marker_group, id, digest) in EVIDENCE_MARKERS_V4 {
		if marker_group == group {
			println!("assertion={id}:{digest}");
			emitted += 1;
		}
	}
	assert!(emitted > 0, "evidence marker group must be registered");
}
