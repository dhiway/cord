import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "../..");
const source = JSON.parse(readFileSync(resolve(root, "docs/sdk/native-route-contract.json"), "utf8"));
if (source.schema !== "cord.native-route-contract.v1" || source.route_count !== source.routes?.length)
  throw new Error("invalid native route contract");
const output = `// Generated by tools/generate-route-contract.ts. Do not edit.\nexport const NATIVE_ROUTE_CONTRACT = ${JSON.stringify(source, null, 2)} as const;\n`;
const path = resolve(import.meta.dirname, "../packages/descriptors/generated/native-route-contract.ts");
if (process.argv.includes("--check")) {
  if (readFileSync(path, "utf8") !== output) throw new Error("native route projection drift; run npm run generate:routes");
} else writeFileSync(path, output);
process.stdout.write(`PASS native route projection: ${source.route_count} routes\n`);
